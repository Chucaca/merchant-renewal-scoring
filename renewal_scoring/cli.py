"""Command line entry point.

    python -m renewal_scoring.cli all        # generate -> score -> evaluate -> report
    python -m renewal_scoring.cli generate --n 20000 --seed 42
    python -m renewal_scoring.cli score
    python -m renewal_scoring.cli evaluate
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import pandas as pd

from .evaluate import SPLIT_DATE, evaluate, make_charts
from .explain import explain
from .features import build_model_matrix, compute_fis
from .score import score_merchants
from .synthetic import SyntheticData, generate

ROOT = Path(__file__).resolve().parents[1]


def _log(msg: str, t0: float) -> None:
    print(f"[{time.perf_counter() - t0:6.1f}s] {msg}", flush=True)


def cmd_generate(args, t0) -> SyntheticData:
    data = generate(n_merchants=args.n, seed=args.seed)
    data.save(args.data_dir)
    _log(f"generated {len(data.merchants):,} merchants x 26 weeks -> {args.data_dir}", t0)
    return data


def cmd_score(args, t0, data: SyntheticData | None = None) -> tuple[pd.DataFrame, pd.DataFrame]:
    data = data or SyntheticData.load(args.data_dir)
    m = data.merchants
    is_train = (pd.to_datetime(m["contract_end"]) < pd.Timestamp(SPLIT_DATE)).to_numpy()
    # FIS uses labels -> fit on the training cohort only.
    fis = compute_fis(data.feature_usage[is_train], m.loc[is_train, "renewed"].to_numpy(), data.feature_names)
    # Peer percentiles are label-free; fit them on the training cohort as well.
    train = SyntheticData(m[is_train].reset_index(drop=True), data.daily_txn[is_train], data.feature_usage[is_train], data.feature_names)
    _, normalizer = score_merchants(train, fis)
    scores, _ = score_merchants(data, fis, normalizer=normalizer)
    Path(args.data_dir).mkdir(parents=True, exist_ok=True)
    scores.to_csv(Path(args.data_dir) / "scores.csv", index=False)
    fis.to_csv(Path(args.data_dir) / "fis.csv", index=False)
    _log(f"scored {len(scores):,} merchants (FIS fit on {is_train.sum():,} training merchants)", t0)
    return scores, fis


def _md_table(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    values = {c: df[c].tolist() for c in cols}  # tolist keeps per-column python types
    for i in range(len(df)):
        cells = [floatfmt.format(values[c][i]) if isinstance(values[c][i], float) else str(values[c][i]) for c in cols]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def write_report(res, fis: pd.DataFrame, charts: list[str], reports_dir: Path) -> Path:
    reports_dir.mkdir(parents=True, exist_ok=True)
    m = res.metrics
    from .synthetic import AHA_FEATURES

    top_fis = fis.head(10)[["feature", "group", "active_signal", "retention_lift", "aha_signal", "fis"]].copy()
    top_fis["hidden_aha_feature"] = top_fis["feature"].isin(AHA_FEATURES).map({True: "yes", False: ""})
    recovered = int(fis.head(10)["feature"].isin(AHA_FEATURES).sum())

    dec = res.deciles[["decile", "merchants", "score_min", "score_max", "churn_rate", "lift", "cum_churn_captured"]].copy()
    dec["merchants"] = dec["merchants"].astype(int)
    abl = res.ablation[["description", "auc", "ks"]].copy()
    abl["description"] = abl["description"].str.strip()

    # sample explanations: one merchant per band
    ex_lines = []
    for band in ["critical", "high", "medium", "low"]:
        sub = res.test[res.test["band"] == band]
        if sub.empty:
            continue
        row = sub.iloc[0].to_dict()
        e = explain(row, use_env=False)
        ex_lines.append(f"**{row['merchant_id']}** ({band}, score {row['score']:.0f}, renewed={row['renewed']})  ")
        ex_lines.append(f"- headline: {e['summary']['headline']}  ")
        ex_lines.append(f"- why: {e['summary']['why']}  ")
        ex_lines.append(f"- next action: {e['summary']['next_action']}  ")
        ex_lines.append(f"- reason codes: {', '.join(r['code'] for r in e['facts']['reasons']) or '-'}\n")

    img = lambda p: f"![{Path(p).stem}](../docs/img/{Path(p).name})"  # noqa: E731
    text = f"""# Evaluation report (synthetic data)

> All numbers below come from **synthetic data** generated by `renewal_scoring.synthetic`.
> They demonstrate the method; they are not results on real merchants.

Time-based split: contracts ending before {m['split_date']} = training cohort
({m['n_train']:,} merchants, used to derive FIS weights, peer percentiles and to
train the benchmark); contracts ending on/after = test cohort ({m['n_test']:,}
merchants, renewal rate {m['renewal_rate_test']:.1%}).

## Headline metrics (test cohort)

| Model | AUC-ROC | 95% bootstrap CI | KS | Top-decile churn lift | Churners caught in riskiest 20% |
|---|---|---|---|---|---|
| Interpretable score | {m['auc_score']:.3f} | {m['auc_score_ci95'][0]:.3f} - {m['auc_score_ci95'][1]:.3f} | {m['ks_score']:.3f} | {m['top_decile_lift_score']:.2f}x | {m['top2_decile_churn_captured_score']:.1%} |
| Black-box GBM ({m['gbm_n_features']} features) | {m['auc_gbm']:.3f} | {m['auc_gbm_ci95'][0]:.3f} - {m['auc_gbm_ci95'][1]:.3f} | {m['ks_gbm']:.3f} | {m['top_decile_lift_gbm']:.2f}x | {m['top2_decile_churn_captured_gbm']:.1%} |

AUC gap (GBM - score), paired bootstrap: **{m['auc_gap_gbm_minus_score']:+.3f}**
(95% CI {m['auc_gap_ci95'][0]:+.3f} to {m['auc_gap_ci95'][1]:+.3f}).

Churn override fired for {m['churn_override_rate']:.1%} of the test cohort; their renewal
rate was {m['churn_override_renewal_rate']:.1%}.

{img(charts[0])}

## Ablation: each component on its own

{_md_table(abl)}

{img(charts[4])}

## Decile lift (interpretable score, decile 1 = riskiest)

{_md_table(dec)}

{img(charts[1])}

## Risk bands

{_md_table(res.band_table)}

{img(charts[2])}

## By (hidden) churn pattern

The generator's ground-truth trajectory is never shown to the scorer; this table
checks the score reacts to each pattern the way the sales team would expect.

{_md_table(res.trajectory_table)}

## Calibration

The score is a ranking index, not a probability. On this synthetic data score/100
happens to track the observed renewal rate fairly closely in the middle but is
over-confident at both ends (the riskiest decile still renews {res.calibration_score['observed'].iloc[0]:.0%},
the safest decile still churns {1 - res.calibration_score['observed'].iloc[-1]:.0%}).
If the sales team needs a probability, fit an isotonic map from score to renewal
rate on the training cohort rather than reading score/100 as a probability.

{img(charts[3])}

## Feature importance scores (FIS), top 10

{recovered} of the top 10 FIS features are among the {len(AHA_FEATURES)} features the
generator secretly made renewal-relevant.

{_md_table(top_fis)}

## Sample explanations (template summaries, offline mode)

{chr(10).join(ex_lines)}
"""
    out = reports_dir / "evaluation.md"
    out.write_text(text, encoding="utf-8")
    (reports_dir / "metrics.json").write_text(json.dumps(m, indent=2), encoding="utf-8")
    fis.to_csv(reports_dir / "fis.csv", index=False, float_format="%.4f")
    return out


def cmd_evaluate(args, t0, data: SyntheticData | None = None, scores=None, fis=None) -> dict:
    data = data or SyntheticData.load(args.data_dir)
    if scores is None:
        scores = pd.read_csv(Path(args.data_dir) / "scores.csv", keep_default_na=False, na_values=[""])
        fis = pd.read_csv(Path(args.data_dir) / "fis.csv")
    X = build_model_matrix(data)
    res = evaluate(scores, X, data.merchants)
    _log("evaluated (incl. GBM benchmark and bootstrap CIs)", t0)
    charts = make_charts(res, args.img_dir)
    report = write_report(res, fis, charts, Path(args.reports_dir))
    _log(f"wrote {report} and {len(charts)} charts -> {args.img_dir}", t0)
    m = res.metrics
    print(
        f"\nAUC score {m['auc_score']:.3f} [{m['auc_score_ci95'][0]:.3f}, {m['auc_score_ci95'][1]:.3f}] | "
        f"AUC GBM {m['auc_gbm']:.3f} | KS {m['ks_score']:.3f} | top-decile lift {m['top_decile_lift_score']:.2f}x"
    )
    return m


def main(argv=None) -> None:
    p = argparse.ArgumentParser(prog="renewal_scoring", description="Interpretable merchant renewal scoring (synthetic data)")
    p.add_argument("command", choices=["generate", "score", "evaluate", "all"])
    p.add_argument("--n", type=int, default=20_000, help="number of merchants")
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--data-dir", default=str(ROOT / "data"))
    p.add_argument("--reports-dir", default=str(ROOT / "reports"))
    p.add_argument("--img-dir", default=str(ROOT / "docs" / "img"))
    args = p.parse_args(argv)
    t0 = time.perf_counter()
    if args.command == "generate":
        cmd_generate(args, t0)
    elif args.command == "score":
        cmd_score(args, t0)
    elif args.command == "evaluate":
        cmd_evaluate(args, t0)
    else:
        data = cmd_generate(args, t0)
        scores, fis = cmd_score(args, t0, data)
        cmd_evaluate(args, t0, data, scores, fis)


if __name__ == "__main__":
    main()
